package com.vehicletracker.api.controller;

import org.springframework.http.CacheControl;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RestController;

/**
 * Tells the website (served by this Java server) to use OUR OWN API
 * instead of Supabase. The website reads this as js/config.js.
 */
@RestController
public class ConfigController {

    @GetMapping(value = "/js/config.js", produces = "text/javascript")
    public ResponseEntity<String> websiteConfig() {
        String script = """
                // Generated by the Java server: use the own REST API (no Supabase).
                export const SUPABASE_CONFIG = null;
                export const API_CONFIG = { baseUrl: '' };
                """;
        return ResponseEntity.ok().cacheControl(CacheControl.noStore()).body(script);
    }
}
