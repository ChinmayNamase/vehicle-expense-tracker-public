// Generates js/config.js from environment variables (or a local .env file).
// Used locally (`npm run config`) and as the build command on Netlify/Vercel,
// so the Supabase URL and publishable key never need to be committed to Git.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

function loadDotEnv(path) {
  if (!existsSync(path)) return;
  for (const line of readFileSync(path, 'utf8').split(/\r?\n/)) {
    const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (!match || process.env[match[1]]) continue;
    process.env[match[1]] = match[2].replace(/^['"]|['"]$/g, '');
  }
}

loadDotEnv('.env');

const url = process.env.SUPABASE_URL || '';
const key = process.env.SUPABASE_PUBLISHABLE_KEY || process.env.SUPABASE_ANON_KEY || '';
// Address of our OWN Java API (e.g. https://vehicle-tracker-api.onrender.com).
// When set, the website uses the own API instead of Supabase.
const apiBaseUrl = (process.env.API_BASE_URL || '').trim().replace(/\/+$/, '');
if (apiBaseUrl && !/^https?:\/\/[^\s]+$/.test(apiBaseUrl)) {
  console.error('API_BASE_URL must look like https://your-api.onrender.com');
  process.exit(1);
}

if (!apiBaseUrl && (!url || !key)) {
  if (existsSync('js/config.js')) {
    console.log('SUPABASE_URL / SUPABASE_PUBLISHABLE_KEY not set; keeping existing js/config.js');
    process.exit(0);
  }
  console.warn('Warning: SUPABASE_URL and SUPABASE_PUBLISHABLE_KEY are not set. See .env.example.');
}

// Refuse to ship a secret key to the browser by mistake.
if (/^sb_secret_/.test(key) || /"role"\s*:\s*"service_role"/.test(decodeJwtPayload(key))) {
  console.error('Refusing to write a secret/service_role key into frontend code. Use the publishable key.');
  process.exit(1);
}

function decodeJwtPayload(token) {
  try {
    return Buffer.from(token.split('.')[1], 'base64url').toString('utf8');
  } catch {
    return '';
  }
}

const output = `// Generated by scripts/generate-config.mjs — do not edit by hand.
export const SUPABASE_CONFIG = {
  url: ${JSON.stringify(url)},
  publishableKey: ${JSON.stringify(key)},
};
export const API_CONFIG = ${apiBaseUrl ? `{ baseUrl: ${JSON.stringify(apiBaseUrl)} }` : 'null'};
`;
writeFileSync('js/config.js', output);
console.log(`Wrote js/config.js (${apiBaseUrl ? `own API: ${apiBaseUrl}` : 'Supabase'})`);
